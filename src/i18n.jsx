const translations = { en, ar };

const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  // Arabic is the default for this deployment - switch to English from the sidebar toggle if needed.
  const [lang, setLang] = useState(localStorage.getItem("collect_lang") || "ar");
  const [theme, setTheme] = useState(localStorage.getItem("collect_theme") || "light");

  const setLanguage = (l) => {
    localStorage.setItem("collect_lang", l);
    setLang(l);
  };

  const toggleTheme = () => {
    setTheme((prev) => {
      const next = prev === "dark" ? "light" : "dark";
      localStorage.setItem("collect_theme", next);
      return next;
    });
  };

  const value = useMemo(() => {
    const t = (key) => translations[lang]?.[key] || translations.en[key] || key;
    const fmtNum = (n) => {
      if (n === null || n === undefined) return "0.00";
      return Number(n).toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
    };
    // Arabic convention places the currency symbol after the number; English before.
    const money = (n) => (lang === "ar" ? `${fmtNum(n)} ${t("currency")}` : `${t("currency")} ${fmtNum(n)}`);

    // Translates a follow-up status VALUE (as stored/matched by the backend, always
    // in English) into the label shown to the user - falls back to the raw value
    // if it's ever an unrecognized status.
    const statusLabel = (raw) => FOLLOWUP_STATUS_LABELS[lang]?.[raw] || raw;

    return { lang, setLanguage, dir: lang === "ar" ? "rtl" : "ltr", t, money, statusLabel, theme, toggleTheme };
  }, [lang, theme]);

  useEffect(() => {
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    document.documentElement.lang = lang;
  }, [lang]);

  useEffect(() => {
    document.documentElement.setAttribute("data-theme", theme);
  }, [theme]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLang() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error("useLang must be used within LanguageProvider");
  return ctx;
}
